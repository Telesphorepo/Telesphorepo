// What a Maven upload will store, worked out in the browser before it is sent. The rules match
// internal/maven/upload.go: one pom (*.pom or pom.xml) plus files named
// <artifactId>-<version>[-<classifier>].<ext>; one file may have another name and becomes the main
// artifact. Coordinates come from the pom; the fields give the ones the pom lacks.

import type { FileRow } from "./types";

export type Coords = { groupId: string; artifactId: string; version: string; packaging: string };
export const coordKeys = ["groupId", "artifactId", "version", "packaging"] as const;

const groupRE = /^[A-Za-z0-9_-]+(\.[A-Za-z0-9_-]+)*$/;
const artifactRE = /^[A-Za-z0-9_][A-Za-z0-9_.-]{0,199}$/;
const versionRE = /^[A-Za-z0-9_][A-Za-z0-9_.+-]{0,199}$/;
const extRE = /^[a-z0-9]+(\.[a-z0-9]+)?$/;
const maxPomBytes = 1 << 20;

export const isPom = (name: string) => {
  const l = name.toLowerCase();
  return l.endsWith(".pom") || l === "pom.xml";
};

/** A pom value the server uses: set, without an unresolved ${property}. */
const usable = (v: string) => v !== "" && !v.includes("${");

/** The usable coordinates of a pom; a missing or unusable one is "". Throws on a pom the server refuses. */
export async function readPom(f: File): Promise<Coords> {
  if (f.size > maxPomBytes) throw new Error(`${f.name} is larger than 1 MiB; the server refuses it.`);
  const doc = new DOMParser().parseFromString(await f.text(), "application/xml");
  const root = doc.documentElement;
  if (!root || doc.getElementsByTagName("parsererror").length) throw new Error(`${f.name} is not valid XML.`);
  const child = (el: Element | undefined, name: string) =>
    el ? [...el.children].find((c) => c.localName === name) : undefined;
  const text = (el: Element | undefined, name: string) => child(el, name)?.textContent?.trim() ?? "";
  const parent = child(root, "parent");
  const c: Coords = {
    groupId: text(root, "groupId") || text(parent, "groupId"),
    artifactId: text(root, "artifactId"),
    version: text(root, "version") || text(parent, "version"),
    packaging: text(root, "packaging"),
  };
  for (const k of coordKeys) if (!usable(c[k])) c[k] = "";
  return c;
}

type Row = FileRow;
export type Plan = {
  rows: Row[];
  /** Why the upload cannot go; "" when it can. */
  problem: string;
  /** The version folder, e.g. "com/acme/app/1.0.0". "" while the coordinates are incomplete. */
  dir: string;
  /** The pom path; generated by the server when no pom is uploaded. */
  pomPath: string;
};

/** Checks the coordinates; the message names what to fix, or "" when they are valid. */
export function coordProblem(c: Coords): string {
  if (!groupRE.test(c.groupId) || c.groupId.length > 200) return "Enter a valid groupId, e.g. com.acme.";
  if (!artifactRE.test(c.artifactId) || c.artifactId === "." || c.artifactId === "..")
    return "Enter a valid artifactId, e.g. app.";
  if (!versionRE.test(c.version) || c.version === "." || c.version === "..") return "Enter a valid version, e.g. 1.0.0.";
  return "";
}

/** The repo path of each file, and what blocks the upload. */
export function plan(files: File[], c: Coords): Plan {
  const poms = files.filter((f) => isPom(f.name));
  const others = files.filter((f) => !isPom(f.name));
  const base = `${c.artifactId}-${c.version}`;
  const cp = coordProblem(c);
  const dir = cp ? "" : `${c.groupId.replaceAll(".", "/")}/${c.artifactId}/${c.version}`;
  const pomPath = dir ? `${dir}/${base}.pom` : "";

  const rows: Row[] = [];
  let problem = poms.length > 1 ? "Upload one pom at a time." : cp;
  if (!files.length) problem = "Add a pom, an artifact, or both.";
  for (const f of poms) rows.push({ file: f, target: pomPath || undefined, error: poms.length > 1 ? "One pom at a time" : undefined });

  let free = false;
  const seen = new Set<string>();
  for (const f of others) {
    if (!dir) {
      rows.push({ file: f });
      continue;
    }
    const row: Row = { file: f };
    const name = f.name;
    let classifier = "";
    let ext = "";
    const rest = name.startsWith(base) ? name.slice(base.length) : "";
    if (rest.startsWith("-") || rest.startsWith(".")) {
      if (rest.startsWith("-")) {
        const dot = rest.indexOf(".");
        if (dot < 2) row.error = `Name it ${base}-<classifier>.<ext>`;
        else {
          classifier = rest.slice(1, dot);
          ext = rest.slice(dot + 1);
        }
      } else ext = rest.slice(1);
    } else if (free) {
      row.error = `Name it ${base}[-<classifier>].<ext>; only one file may have another name`;
    } else {
      free = true;
      const dot = name.lastIndexOf(".");
      if (dot < 1) row.error = "The file has no extension";
      else ext = name.slice(dot + 1).toLowerCase();
    }
    if (!row.error && (!extRE.test(ext) || (classifier && !artifactRE.test(classifier))))
      row.error = "Invalid classifier or extension";
    if (!row.error) {
      const target = `${dir}/${base}${classifier ? "-" + classifier : ""}.${ext}`;
      if (seen.has(target)) row.error = "Another file goes to the same path";
      else {
        seen.add(target);
        row.target = target;
      }
    }
    if (row.error && !problem) problem = `${name}: ${row.error.charAt(0).toLowerCase()}${row.error.slice(1)}.`;
    rows.push(row);
  }
  return { rows, problem, dir, pomPath };
}
